"""Shared helpers: call Claude and get back structured data safely."""

import json
import os

# The model can be changed without editing code: export CLAUDE_MODEL=...
MODEL = os.environ.get("CLAUDE_MODEL", "claude-sonnet-5-5")


def call_claude_structured(system_prompt: str, user_prompt: str, schema: dict,
                           tool_name: str = "submit_result", max_tokens: int = 8000) -> dict:
    """Ask Claude to answer by filling in a schema (tool use).

    Answering through a tool means the result comes back as structured data
    that matches `schema`, so there is no fragile text-to-JSON parsing.
    If Claude replies in plain text instead, it is asked once more to use the tool.
    """
    from anthropic import Anthropic  # imported here so --dry-run works without the package

    client = Anthropic()  # reads ANTHROPIC_API_KEY from the environment
    tools = [{
        "name": tool_name,
        "description": "Submit the finished result in the required structure. Always use this tool to answer.",
        "input_schema": schema,
    }]
    messages = [{"role": "user", "content": user_prompt}]

    for attempt in range(2):
        response = client.messages.create(
            model=MODEL,
            max_tokens=max_tokens,
            system=system_prompt,
            messages=messages,
            tools=tools,
            tool_choice={"type": "auto"},
        )
        if response.stop_reason == "max_tokens":
            raise RuntimeError("Claude's answer was cut off (max_tokens). Try fewer items per run.")
        for block in response.content:
            if block.type == "tool_use" and block.name == tool_name:
                return block.input
        # No tool call: keep the conversation going and ask explicitly once.
        messages = messages + [
            {"role": "assistant", "content": response.content},
            {"role": "user", "content": f"Please submit your answer now using the {tool_name} tool."},
        ]
    raise RuntimeError("Claude did not return a structured result after two attempts.")


def save(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"  wrote {path}")


def save_json(path: str, data: dict) -> None:
    save(path, json.dumps(data, indent=2))


